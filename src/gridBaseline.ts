export const BASELINE: Record<"fixed" | "adaptive", BaselineTable> = { fixed: FIXED, adaptive: ADAPTIVE };

/** Подпись порога так же, как в отчётах: fixed "0.13%", adaptive "0.7x". */
function paramLabel(mode: "fixed" | "adaptive", param: number): string {
  return mode === "fixed" ? `${(param * 100).toFixed(2)}%` : `${param.toFixed(1)}x`;
}

/**
 * Прибавляет базу к сетке (выигрыши к выигрышам, всего к всего по каждой ячейке).
 * grid — карта вида "порог_окно" -> { win, total }, как строит gridForCoin в парсере.
 */
export function applyBaseline(
  grid: Map<string, { win: number; total: number }>,
  coin: string,
  mode: "fixed" | "adaptive",
  params: number[],
  windows: number[],
): void {
  const byParam = BASELINE[mode][coin];
  if (!byParam) return;
  for (const param of params) {
    const cells = byParam[paramLabel(mode, param)];
    if (!cells) continue;
    for (const windowSec of windows) {
      const col = BASELINE_WINDOWS.indexOf(windowSec);
      if (col === -1) continue;
      const m = /^(\d+)\/(\d+)$/.exec(cells[col] ?? "");
      if (!m) continue;
      const cell = grid.get(`${param}_${windowSec}`);
      if (!cell) continue;
      cell.win += Number(m[1]);
      cell.total += Number(m[2]);
    }
  }
}
